# Shared helpers, sourced by the other scripts.
EXT=/mnt/us/extensions/kindlehome
PIDFILE=/tmp/kindlehome-watchdog.pid
MODEFILE=/tmp/kindlehome.mode   # "browser" or "fullscreen", written by start.sh
LOG=/tmp/kindlehome.log
LIGHTPID=/tmp/kindlehome-light.pid
LIGHTSTATE=/tmp/kindlehome.light
TOUCHFILE=/tmp/kindlehome.touch
APP_ID=com.kindlehome.kiosk
APPREG=/var/local/appreg.db
# The app's localStorage (LocalStoragePath in app/config.xml), read by the watchdog
APPSTORE=$EXT/app/storage/file__0.localstorage
CRASHFILE=/mnt/us/kindlehome-crash.txt
. "$EXT/config.sh"

# Everything (including lipc errors) goes to the log for troubleshooting.
exec >>"$LOG" 2>&1

log() { echo "$(date '+%F %T') $*"; }

# The top bar ("pillow") is the status line and browser toolbar.
hide_bars() {
    log "hiding top bar"
    lipc-set-prop com.lab126.pillow disableEnablePillow disable
}

show_bars() {
    log "showing top bar"
    lipc-set-prop com.lab126.pillow disableEnablePillow enable
}

RESTARTING=/tmp/kindlehome.restarting   # exists while open_page switches apps
HOME_APP=com.lab126.booklet.home

# wait_for <seconds> <test...>: poll once a second until the test succeeds.
wait_for() {
    max=$1; shift
    n=0
    while ! "$@" && [ "$n" -lt "$max" ]; do
        sleep 1
        n=$((n + 1))
    done
}
at_home() { [ "$(active_app)" = "$HOME_APP" ]; }
app_is_active() { [ "$(active_app)" = "$APP_ID" ]; }
app_gone() { ! app_process_running; }

# Starting an app while another one is still switching makes the Kindle show an
# "application error" popup: the app being left (e.g. KUAL closing its menu) fails to
# pause in time. So first get to the home screen, like the app's Exit link does, and
# let everything settle. Leaving also unloads the app, a real restart that frees memory.
go_home() {
    if [ "$(active_app)" = "$1" ]; then
        log "going to the home screen to restart $1"
        lipc-set-prop com.lab126.appmgrd start "app://$HOME_APP"
    fi
    wait_for 30 at_home
    log "active app before opening: $(active_app)"
}

open_page() {
    touch "$RESTARTING"
    if [ "$(cat "$MODEFILE" 2>/dev/null)" = "fullscreen" ]; then
        go_home "$APP_ID"
        wait_for 30 app_gone   # unloadOnPause: its process ends once it's paused
        sleep 3
        log "opening fullscreen app ($KV_URL)"
        lipc-set-prop com.lab126.appmgrd start "app://$APP_ID"
        wait_for 30 app_is_active
    else
        go_home com.lab126.browser
        lipc-set-prop com.lab126.appmgrd stop com.lab126.browser   # paused now, so this is quiet
        sleep 3
        log "opening $KV_URL in the browser"
        lipc-set-prop com.lab126.appmgrd start "app://com.lab126.browser?view=$KV_URL"
    fi
    rm -f "$RESTARTING"
}

# Register the fullscreen web app in the Kindle's app registry, like Komic does.
install_app() {
    mkdir -p "$EXT/app/storage"
    printf '// Generated by bin/start.sh, do not edit.\nwindow.KV_URL = "%s";\nwindow.KV_APP_MODE = "%s";\n' \
        "$KV_URL" "${KV_APP_MODE:-frame}" > "$EXT/app/config.js"
    sqlite3 "$APPREG" "
        DELETE FROM properties WHERE handlerId = '$APP_ID';
        DELETE FROM handlerIds WHERE handlerId = '$APP_ID';
        INSERT INTO handlerIds VALUES ('$APP_ID');
        INSERT INTO properties VALUES ('$APP_ID', 'command', '/usr/bin/mesquite -l $APP_ID -c file://$EXT/app/');
        INSERT INTO properties VALUES ('$APP_ID', 'unloadPolicy', 'unloadOnPause');
    " && log "app registered" || log "app registration FAILED"
}

uninstall_app() {
    sqlite3 "$APPREG" "
        DELETE FROM properties WHERE handlerId = '$APP_ID';
        DELETE FROM handlerIds WHERE handlerId = '$APP_ID';
    " && log "app unregistered"
}

# Called by the watchdog (never from a KUAL action, which must return quickly):
# wait until the browser is up, as it redraws the bar when it starts.
hide_bars_if_configured() {
    if [ "${KV_HIDE_BARS:-0}" = "1" ]; then
        sleep 8
        hide_bars
    fi
}

# start_detached <script> [args]: run a script in the background so that it
# survives KUAL closing its menu (KUAL may kill its whole process group).
# (The Kindle's busybox ash has no `command` builtin, so probe paths directly.)
start_detached() {
    for s in /usr/bin/setsid /bin/setsid /sbin/setsid /usr/sbin/setsid; do
        if [ -x "$s" ]; then
            "$s" /bin/sh "$@" </dev/null >/dev/null 2>&1 &
            return
        fi
    done
    /bin/sh "$@" </dev/null >/dev/null 2>&1 &
}

# The touchscreen's /dev/input/eventN, from /proc/bus/input/devices.
find_touch_dev() {
    awk '/^N:/ { name = tolower($0) }
         /^H:/ && name ~ /zforce|touch|cyttsp|elan|pixcir|cypress/ && match($0, /event[0-9]+/) {
             print "/dev/input/" substr($0, RSTART, RLENGTH); exit
         }' /proc/bus/input/devices 2>/dev/null
}

# Seconds since the page last reported typing (asked from the server), empty if unknown.
typing_age() {
    base=$(echo "$KV_URL" | sed -n 's#^\(http://[^/?]*\).*#\1#p')
    [ -n "$base" ] && wget -q -T 5 -O - "$base/typing" 2>/dev/null
}

light_running() {
    [ -f "$LIGHTPID" ] && kill -0 "$(cat "$LIGHTPID")" 2>/dev/null
}

start_light() {
    [ "${KV_LIGHT_AUTO:-1}" = "1" ] || return 0
    light_running || start_detached "$EXT/bin/light.sh"
}

stop_light() {
    if [ -f "$LIGHTPID" ]; then
        # light.sh runs in its own process group (setsid): stop it with its timer and blocked read
        pid=$(cat "$LIGHTPID")
        kill -TERM -"$pid" 2>/dev/null || kill "$pid" 2>/dev/null
        rm -f "$LIGHTPID"
    fi
}

# "r" while the fullscreen app runs, "x" after its Exit link was used (set by app/index.html).
# Single letters, so the result is the same whether WebKit stored the value as text or UTF-16.
app_state() {
    sqlite3 "$APPSTORE" "SELECT value FROM ItemTable WHERE key = 'kv-state';" 2>/dev/null
}

active_app() {
    lipc-get-prop com.lab126.appmgrd activeApp 2>/dev/null
}

# cmdline of each process (processes that end while we look are skipped silently)
cmdlines() {
    for d in /proc/[0-9]*; do
        { echo "$d $(tr '\0' ' ' < "$d/cmdline")"; } 2>/dev/null
    done
}

app_process_running() {
    cmdlines | grep -q "[m]esquite.*$APP_ID"
}

# One line for the log: battery, free memory and the app's memory use (to spot leaks).
status_line() {
    avail=$(awk '/^(MemFree|Buffers|Cached):/ { s += $2 } END { print s }' /proc/meminfo)
    rss=""
    for d in $(cmdlines | grep -e "[m]esquite.*$APP_ID" -e "[m]esquite.*com.lab126.browser" | cut -d' ' -f1); do
        rss="$rss $(awk '/^VmRSS:/ { print $2 }' "$d/status" 2>/dev/null)kB"
    done
    echo "battery $(lipc-get-prop com.lab126.powerd battLevel 2>/dev/null)%," \
         "free ${avail}kB, page${rss:- not running}"
}

# The newest rotated syslog (tinyrot rotates often; once it did so seconds before a crash
# and the current file held almost nothing), empty if none.
prev_syslog() {
    ls -t /var/local/log/messages* /var/log/messages.* 2>/dev/null | head -n 1
}

# syslog_tail <lines>: the end of the syslog, continuing into the rotated file if needed.
syslog_tail() {
    prev=$(prev_syslog)
    {
        case "$prev" in
            *.gz) gunzip -c "$prev" ;;
            ?*)   cat "$prev" ;;
        esac
        cat /var/log/messages
    } 2>/dev/null | tail -n "$1"
}

EVENTFILE=/mnt/us/kindlehome-events.txt

# file_size <file>: its size in bytes (from the directory entry, the file isn't read).
file_size() {
    set -- $(ls -ln "$1" 2>/dev/null)
    echo "${5:-0}"
}

# record_events <offset> <active app>: called every few minutes by the watchdog with the
# syslog size from its last call; prints the current size for the next call. Copies warnings,
# errors, popups and app exits logged since then to $EVENTFILE (visible over USB), with 5 lines
# of context, before log rotation loses them: e.g. which program causes an "application error"
# popup at night. Cheap on old hardware: only the new part of the syslog is read, no temp
# files, and the Kindle drive is written only when something matched.
record_events() {
    size=$(file_size /var/log/messages)
    echo "$size"
    [ -n "$1" ] || return 0   # first call: just remember where we are
    [ "$size" -eq "$1" ] && return 0
    if [ "$size" -gt "$1" ]; then
        max=$((size - $1))    # lines written while we read are left for the next call
        tail -c +$(($1 + 1)) /var/log/messages
    else                      # rotated: the rest of the old file, then the new one
        max=-1
        prev=$(prev_syslog)
        case "$prev" in
            *.gz) gunzip -c "$prev" | tail -c +$(($1 + 1)) ;;
            ?*)   tail -c +$(($1 + 1)) "$prev" ;;
        esac
        cat /var/log/messages
    fi 2>/dev/null | awk -v max="$max" -v f="$EVENTFILE" \
        -v hdr="=== $(date '+%F %T') active app: $2" '
        function out(l) { if (!n++) print hdr >> f; print l >> f }
        max >= 0 { got += length($0) + 1; if (got > max) exit }
        { i = NR; b[i % 6] = $0 }
        /getactiveAppInt|lipc:axstime|cannot find callback function|button-(press|release)/ { next }
        /^[0-9]+:[0-9]+ [^ ]+: [EWC] / || /pillow|[Aa]lert|[Dd]ialog|abnormal_exit=1|exited_app|[Cc]rash|[Ee]rror/ {
            s = i - 5; if (s <= last) s = last + 1
            if (last && s > last + 1) out("...")
            for (j = s; j <= i; j++) out(b[j % 6])
            last = i
        }
        END { exit n ? 0 : 1 }' || return 0
    # something was written: keep the file small
    if [ "$(file_size "$EVENTFILE")" -gt 400000 ]; then
        tail -n 3000 "$EVENTFILE" > "$EVENTFILE.tmp" && mv -f "$EVENTFILE.tmp" "$EVENTFILE"
    fi
}

# What was tapped right before the app was last paused, e.g. "simple_alert default_status_bar
# search_bar" (pillow logs each tap's target): the toolbar's search bar opens the home screen.
taps_before_pause() {
    syslog_tail 1000 | awk -v app="$APP_ID" '
        /button-press:target=/ { s = $0; sub(/.*button-press:target=/, "", s); sub(/[,:].*/, "", s); t[NR] = s }
        index($0, "lipc_id=" app ",state=PAUSE_SENT") {
            last = ""
            for (i = NR - 40; i < NR; i++) if (i in t) last = last " " t[i]
        }
        END { sub(/^ /, "", last); print last }'
}

# What the system logged around an unexpected exit, for troubleshooting (visible over USB).
# The previous report is kept as kindlehome-crash.prev.txt.
crash_report() {
    [ -f "$CRASHFILE" ] && mv -f "$CRASHFILE" "${CRASHFILE%.txt}.prev.txt"
    {
        echo "=== $(date '+%F %T') $1"
        echo "=== status";       status_line
        echo "=== taps before the app was paused"; taps_before_pause
        echo "=== popups and taps (pillow)"
        syslog_tail 3000 | grep -i -e pillow -e alert | tail -n 40
        echo "=== syslog (rotated file: $(prev_syslog))"; syslog_tail 300
        echo "=== dmesg";        dmesg 2>&1 | tail -n 60
        echo "=== KindleHome log"; tail -n 40 "$LOG" 2>&1
    } > "$CRASHFILE" 2>&1
}

stop_watchdog() {
    if [ -f "$PIDFILE" ]; then
        kill "$(cat "$PIDFILE")" 2>/dev/null
        rm -f "$PIDFILE"
    fi
}
