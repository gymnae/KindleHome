# Shared helpers, sourced by the other scripts.
EXT=/mnt/us/extensions/kindlehome
PIDFILE=/tmp/kindlehome-watchdog.pid
MODEFILE=/tmp/kindlehome.mode   # "browser" or "fullscreen", written by start.sh
LOG=/tmp/kindlehome.log
LIGHTPID=/tmp/kindlehome-light.pid
LIGHTSTATE=/tmp/kindlehome.light
TOUCHFILE=/tmp/kindlehome.touch
APP_ID=com.kindlehome.kiosk
APPREG=/var/local/appreg.db
# The app's localStorage (LocalStoragePath in app/config.xml), read by the watchdog
APPSTORE=$EXT/app/storage/file__0.localstorage
CRASHFILE=/mnt/us/kindlehome-crash.txt
. "$EXT/config.sh"

# Everything (including lipc errors) goes to the log for troubleshooting.
exec >>"$LOG" 2>&1

log() { echo "$(date '+%F %T') $*"; }

# The top bar ("pillow") is the status line and browser toolbar.
hide_bars() {
    log "hiding top bar"
    lipc-set-prop com.lab126.pillow disableEnablePillow disable
}

show_bars() {
    log "showing top bar"
    lipc-set-prop com.lab126.pillow disableEnablePillow enable
}

# Starting an app while it runs makes the Kindle show an "application error" popup
# (this happened with the nightly relaunch), so stop it first. That's also a real
# restart, which frees its memory.
stop_if_active() {
    if [ "$(active_app)" = "$1" ]; then
        log "stopping $1 to restart it"
        lipc-set-prop com.lab126.appmgrd stop "$1"
        # wait until it's really gone (a fixed 5 s may be too short), at most 30 s
        n=0
        while [ "$(active_app)" = "$1" ] && [ "$n" -lt 30 ]; do
            sleep 1
            n=$((n + 1))
        done
        log "stopped $1 after ${n}s"
        sleep 3
    fi
}

open_page() {
    if [ "$(cat "$MODEFILE" 2>/dev/null)" = "fullscreen" ]; then
        stop_if_active "$APP_ID"
        log "opening fullscreen app ($KV_URL)"
        lipc-set-prop com.lab126.appmgrd start "app://$APP_ID"
    else
        stop_if_active com.lab126.browser
        log "opening $KV_URL in the browser"
        lipc-set-prop com.lab126.appmgrd start "app://com.lab126.browser?view=$KV_URL"
    fi
}

# Register the fullscreen web app in the Kindle's app registry, like Komic does.
install_app() {
    mkdir -p "$EXT/app/storage"
    printf '// Generated by bin/start.sh, do not edit.\nwindow.KV_URL = "%s";\nwindow.KV_APP_MODE = "%s";\n' \
        "$KV_URL" "${KV_APP_MODE:-frame}" > "$EXT/app/config.js"
    sqlite3 "$APPREG" "
        DELETE FROM properties WHERE handlerId = '$APP_ID';
        DELETE FROM handlerIds WHERE handlerId = '$APP_ID';
        INSERT INTO handlerIds VALUES ('$APP_ID');
        INSERT INTO properties VALUES ('$APP_ID', 'command', '/usr/bin/mesquite -l $APP_ID -c file://$EXT/app/');
        INSERT INTO properties VALUES ('$APP_ID', 'unloadPolicy', 'unloadOnPause');
    " && log "app registered" || log "app registration FAILED"
}

uninstall_app() {
    sqlite3 "$APPREG" "
        DELETE FROM properties WHERE handlerId = '$APP_ID';
        DELETE FROM handlerIds WHERE handlerId = '$APP_ID';
    " && log "app unregistered"
}

# Called by the watchdog (never from a KUAL action, which must return quickly):
# wait until the browser is up, as it redraws the bar when it starts.
hide_bars_if_configured() {
    if [ "${KV_HIDE_BARS:-0}" = "1" ]; then
        sleep 8
        hide_bars
    fi
}

# start_detached <script> [args]: run a script in the background so that it
# survives KUAL closing its menu (KUAL may kill its whole process group).
# (The Kindle's busybox ash has no `command` builtin, so probe paths directly.)
start_detached() {
    for s in /usr/bin/setsid /bin/setsid /sbin/setsid /usr/sbin/setsid; do
        if [ -x "$s" ]; then
            "$s" /bin/sh "$@" </dev/null >/dev/null 2>&1 &
            return
        fi
    done
    /bin/sh "$@" </dev/null >/dev/null 2>&1 &
}

# The touchscreen's /dev/input/eventN, from /proc/bus/input/devices.
find_touch_dev() {
    awk '/^N:/ { name = tolower($0) }
         /^H:/ && name ~ /zforce|touch|cyttsp|elan|pixcir|cypress/ && match($0, /event[0-9]+/) {
             print "/dev/input/" substr($0, RSTART, RLENGTH); exit
         }' /proc/bus/input/devices 2>/dev/null
}

# Seconds since the page last reported typing (asked from the server), empty if unknown.
typing_age() {
    base=$(echo "$KV_URL" | sed -n 's#^\(http://[^/?]*\).*#\1#p')
    [ -n "$base" ] && wget -q -T 5 -O - "$base/typing" 2>/dev/null
}

light_running() {
    [ -f "$LIGHTPID" ] && kill -0 "$(cat "$LIGHTPID")" 2>/dev/null
}

start_light() {
    [ "${KV_LIGHT_AUTO:-1}" = "1" ] || return 0
    light_running || start_detached "$EXT/bin/light.sh"
}

stop_light() {
    if [ -f "$LIGHTPID" ]; then
        # light.sh runs in its own process group (setsid): stop it with its timer and blocked read
        pid=$(cat "$LIGHTPID")
        kill -TERM -"$pid" 2>/dev/null || kill "$pid" 2>/dev/null
        rm -f "$LIGHTPID"
    fi
}

# "r" while the fullscreen app runs, "x" after its Exit link was used (set by app/index.html).
# Single letters, so the result is the same whether WebKit stored the value as text or UTF-16.
app_state() {
    sqlite3 "$APPSTORE" "SELECT value FROM ItemTable WHERE key = 'kv-state';" 2>/dev/null
}

active_app() {
    lipc-get-prop com.lab126.appmgrd activeApp 2>/dev/null
}

# One line for the log: battery, free memory and the app's memory use (to spot leaks).
status_line() {
    avail=$(awk '/^(MemFree|Buffers|Cached):/ { s += $2 } END { print s }' /proc/meminfo)
    rss=""
    for d in /proc/[0-9]*; do
        case "$(tr '\0' ' ' < "$d/cmdline" 2>/dev/null)" in
            *mesquite*"$APP_ID"*|*mesquite*com.lab126.browser*) rss="$rss $(awk '/^VmRSS:/ { print $2 }' "$d/status")kB" ;;
        esac
    done
    echo "battery $(lipc-get-prop com.lab126.powerd battLevel 2>/dev/null)%," \
         "free ${avail}kB, page${rss:- not running}"
}

# What the system logged around an unexpected exit, for troubleshooting (visible over USB).
crash_report() {
    {
        echo "=== $(date '+%F %T') $1"
        echo "=== status";       status_line
        echo "=== syslog";       tail -n 300 /var/log/messages 2>&1
        echo "=== dmesg";        dmesg 2>&1 | tail -n 60
        echo "=== KindleHome log"; tail -n 40 "$LOG" 2>&1
    } > "$CRASHFILE" 2>&1
}

stop_watchdog() {
    if [ -f "$PIDFILE" ]; then
        kill "$(cat "$PIDFILE")" 2>/dev/null
        rm -f "$PIDFILE"
    fi
}
